#!/usr/bin/env bash
# Reject AI attribution in PR commit messages.
#
# AGENTS.md: "Never add 'Co-Authored-By' or AI attribution to commits. Use
# conventional commits only." Nothing enforced it. A PR landed with
# `Co-Authored-By: Codebuff <noreply@codebuff.com>` and
# `Generated with Codebuff 🤖` and every check stayed green, because the four
# enforced PR rules (linked+approved issue, one type:* label, conventional
# branch) say nothing about trailers.
#
# WHY THIS IS NOT A BLANKET BAN ON `Co-Authored-By`. The release automation
# signs every release commit. Measured over the last 200 commits on main:
#
#   Co-authored-by: release-plz-tu-repo[bot]   x11  (every `chore: release`)
#   Co-Authored-By: Claude Opus 4.8            x11  (human commits)
#   Co-Authored-By: Codebuff                   x1   (a PR branch)
#
# Banning the trailer outright would fail the release flow, which is the one
# co-author the repository genuinely depends on. So the rule fails CLOSED on
# an ALLOWLIST: a co-author is accepted only when it names a known automation
# actor. Everything else is attribution — Claude, Codebuff, a colleague, or a
# tool that does not exist yet. A new legitimate actor is a decision made by
# adding one entry here, never a drift that slips through.
#
# `Generated with …` / `Generated by …` and the robot emoji are rejected
# outright. They name no co-author at all and carry only attribution meaning.
#
# Forward-looking only: this judges PR commits, never history. The 11 commits
# already on main carrying `Co-Authored-By: Claude Opus 4.8` are not touched.
#
# Usage:
#   PR_NUMBER=<n> REPO=<owner/repo> GH_TOKEN=<t> bash scripts/check_no_ai_attribution.sh
#       fetch the PR's commit messages from the API and scan them
#   bash scripts/check_no_ai_attribution.sh --fixture <file>
#       scan NUL-separated messages read from <file> (used by the test harness)
set -euo pipefail

# Co-authors accepted by name, matched case-insensitively against the whole
# trailer value. Short and explicit on purpose.
ALLOWED_CO_AUTHORS=(
  "release-plz"
  "github-actions[bot]"
  "dependabot"
  "renovate"
)

# scan_message <message> -> prints one line per offence, nothing when clean.
#
# Only the TRAILER BLOCK is scanned — the contiguous lines after the final
# blank line, which is where git trailers live by definition. A marker quoted
# in body prose (discussing the rule, citing the evidence, explaining the
# allowlist) is not a trailer and must not fire. Scanning the whole body
# false-positived on exactly that: a commit explaining the check quoted
# "Generated with Codebuff", which the body-wide rule reported as an offence.
scan_message() {
  local msg="$1"
  local trailers subject
  trailers="$(printf '%s\n' "$msg" | awk 'BEGIN{buf=""} /^[[:space:]]*$/{buf=""; next} {buf = (buf == "" ? $0 : buf ORS $0)} END{print buf}')"
  subject="$(printf '%s' "$msg" | head -1)"

  # A blank message is itself an anomaly: there is nothing to review and
  # nothing to authorize. Fail closed rather than wave it through.
  if [ -z "$(printf '%s' "$msg" | tr -d '[:space:]')" ]; then
    printf 'empty-message\t(no subject)\n'
    return 0
  fi

  # 1. Attribution markers with no co-author meaning to allow.
  if printf '%s\n' "$trailers" | grep -qiE '^[[:space:]]*generated[[:space:]]+(with|by)[[:space:]]'; then
    printf 'generated-marker\t%s\n' "$subject"
    return 0
  fi
  if printf '%s\n' "$trailers" | grep -q '🤖'; then
    printf 'robot-emoji\t%s\n' "$subject"
    return 0
  fi

  # 2. Co-author trailers: accepted only for a known automation actor.
  # `grep -F` is load-bearing: `github-actions[bot]` is a literal bracket pair,
  # and under `-E`/`-G` `[bot]` would be a character class matching
  # `github-actionsb` while MISSING the real string.
  local line value actor allowed
  while IFS= read -r line; do
    [ -n "$line" ] || continue
    value="${line#*:}"
    value="$(printf '%s' "$value" | sed -E 's/^[[:space:]]+|[[:space:]]+$//g')"
    allowed=false
    for actor in "${ALLOWED_CO_AUTHORS[@]}"; do
      if printf '%s' "$value" | grep -qiF -- "$actor"; then
        allowed=true
        break
      fi
    done
    if [ "$allowed" = false ]; then
      printf 'co-author\t%s\t%s\n' "$subject" "$value"
    fi
  done < <(printf '%s\n' "$trailers" | grep -iE '^[[:space:]]*co-?authored-by:' || true)
}

# scan_messages <messages...> -> aggregate and exit non-zero on any offence.
scan_messages() {
  local msg offences=() total=0
  for msg in "$@"; do
    while IFS=$'\t' read -r kind subject value; do
      offences+=("[$kind] $subject :: ${value:-}")
    done < <(scan_message "$msg")
  done

  total="${#offences[@]}"
  if [ "$total" -eq 0 ]; then
    echo "OK: ningún commit lleva atribución de AI."
    return 0
  fi

  echo "::error::AGENTS.md prohíbe 'Co-Authored-By' y atribución de AI en commits."
  echo "::error::$total commit(s) afectado(s):"
  local o
  for o in "${offences[@]}"; do
    echo "::error::  - $o"
  done
  cat >&2 <<'NOTE'

Qué hacer: reescribir el/los commit(s) sin el trailer.

  git rebase -i <base>     # marca el commit con `reword` y quita las líneas
                           #   `Generated with …` / `Co-Authored-By: <AI>`

La co-autoría de automatización (release-plz, github-actions, dependabot,
renovate) SÍ está permitida. Un humano o una herramienta de AI nombrados como
co-autores, no. Añadir un actor nuevo a ALLOWED_CO_AUTHORS es una decisión
explícita, no un default.

NOTE
  return 1
}

# ---------------------------------------------------------------------------
# Input modes
# ---------------------------------------------------------------------------
if [ "${1:-}" = "--fixture" ]; then
  # NUL-separated messages, for the test harness. Keeps the scanner free of
  # API and network concerns.
  FIXTURE="${2:?--fixture requires a file}"
  [ -r "$FIXTURE" ] || { echo "::error::fixture no legible: $FIXTURE" >&2; exit 1; }
  mapfile -d '' -t MESSAGES < "$FIXTURE"
  if [ "${#MESSAGES[@]}" -eq 0 ]; then
    echo "::error::el fixture no contiene ningún mensaje." >&2
    exit 1
  fi
  scan_messages "${MESSAGES[@]}"
  exit $?
fi

: "${PR_NUMBER:?PR_NUMBER is required}"
: "${REPO:?REPO is required (owner/name)}"
: "${GH_TOKEN:?GH_TOKEN is required}"

# The workflow checkout is depth 1, so the PR's commits are not present
# locally. Read each message from the API instead — one call per commit, and
# PRs in this repository carry a handful of them.
mapfile -t SHAS < <(
  gh api "repos/$REPO/pulls/$PR_NUMBER/commits" --paginate --jq '.[].sha' 2>/dev/null || true
)
if [ "${#SHAS[@]}" -eq 0 ]; then
  echo "::error::No se pudo leer ningún commit del PR $PR_NUMBER en $REPO." >&2
  exit 1
fi

MESSAGES=()
for sha in "${SHAS[@]}"; do
  msg="$(gh api "repos/$REPO/commits/$sha" --jq '.commit.message' 2>/dev/null || true)"
  if [ -z "$msg" ]; then
    echo "::error::No se pudo leer el mensaje del commit $sha." >&2
    exit 1
  fi
  MESSAGES+=("$msg")
done

scan_messages "${MESSAGES[@]}"
